<?php

declare(strict_types=1);

namespace OCA\FormVox\Service;

use OCP\IL10N;
use Psr\Log\LoggerInterface;

/**
 * The one check of a form's structure, on every way a form is written: the editor, a new form, templates, AI,
 * the Microsoft import and WebDAV (review V5). What would break the form or its submissions is refused with a
 * message per question; leftovers nobody can see in the editor are removed (PO). Responses and the index are
 * not its business, and nothing that only reads or answers a form runs it.
 */
class FormSchemaValidator {
	public const MAX_QUESTIONS = 500;
	public const MAX_TITLE = 255;
	public const MAX_OPTIONS = 100;
	public const MAX_MATRIX_ROWS = 50;
	public const MAX_MATRIX_COLUMNS = 20;
	public const MAX_TABLE_COLUMNS = 20;
	public const MAX_TABLE_ROWS = 200;
	public const SCALE_MAX = 10;
	public const RATING_MAX = 10;
	public const MAX_FILES = 20;
	public const MAX_FILE_SIZE_MB = 100;
	private const MAX_PATTERN = 500;
	private const MAX_CONDITION_DEPTH = 10;

	public const QUESTION_TYPES = ['text', 'textarea', 'number', 'choice', 'multiple', 'dropdown', 'consent', 'date', 'datetime', 'time',
		'scale', 'rating', 'matrix', 'table', 'file', 'section', 'descriptor'];
	public const OPERATORS = ['equals', 'notEquals', 'contains', 'notContains', 'isEmpty', 'isNotEmpty', 'greaterThan', 'lessThan', 'in', 'notIn'];

	/** Fields every question may carry; the legacy ones are harmless and never rendered. */
	private const COMMON_FIELDS = ['id', 'type', 'question', 'description', 'required', 'showIf', 'color', 'sectionId', 'autoGenerated',
		'useAsRespondentEmail', 'placeholder', 'order', 'allowOther', 'consentLabel'];

	private const HEADING_LEVELS = ['h1', 'h2', 'h3', 'h4', 'h5', 'h6'];

	/** Names older forms used, and what they are called now. */
	private const OLD_NAMES = [
		'scale' => ['min' => 'scaleMin', 'max' => 'scaleMax', 'minLabel' => 'scaleMinLabel', 'maxLabel' => 'scaleMaxLabel'],
		'rating' => ['max' => 'ratingMax'],
	];

	/** What each type adds; anything else on a question is a leftover (from a type it had before, or unknown). */
	private const TYPE_FIELDS = [
		'text' => ['validation', 'maxLength'],
		'textarea' => ['validation', 'maxLength'],
		'number' => ['min', 'max', 'validation'],
		'choice' => ['options'],
		'dropdown' => ['options'],
		'multiple' => ['options', 'minSelections', 'maxSelections'],
		'consent' => [],
		'date' => ['dateMin', 'dateMax'],
		'datetime' => ['dateMin', 'dateMax'],
		'time' => ['timeMin', 'timeMax'],
		'scale' => ['scaleMin', 'scaleMax', 'scaleMinLabel', 'scaleMaxLabel'],
		'rating' => ['ratingMax'],
		'matrix' => ['rows', 'columns'],
		'table' => ['columns', 'minRows', 'maxRows'],
		'file' => ['allowedTypePreset', 'allowedTypes', 'maxFileSize', 'maxFiles'],
		'section' => [],
		'descriptor' => ['descriptorAlign'],
	];

	private const COLORS = '/^(#[0-9a-fA-F]{3,8})?$/';
	private const ALIGNMENTS = ['left', 'center', 'right'];
	private const FILE_PRESETS = ['images', 'documents', 'pdf', 'all', 'custom'];
	private const TABLE_INPUTS = ['text', 'number', 'date', 'dropdown'];

	private const BOOLEAN_SETTINGS = ['anonymous', 'allow_multiple', 'require_login', 'notify_owner', 'sendConfirmationEmail', 'confirmationEmailPdf', 'keepResponsePdf'];
	private const KNOWN_SETTINGS = ['anonymous', 'allow_multiple', 'require_login', 'notify_owner', 'sendConfirmationEmail', 'confirmationEmailPdf', 'keepResponsePdf',
		'limit_message', 'confirmationEmailSubject', 'confirmationEmailBody', 'public_token', 'share_password',
		'share_expires_at', 'share_starts_at', 'max_responses', 'allowed_users', 'allowed_groups', 'notify_recipients',
		'api_keys', 'webhooks', 'share_password_hash', 'has_share_password'];

	public function __construct(
		private IL10N $l,
		private LoggerInterface $logger,
	) {
	}

	/**
	 * The form as it may be stored: leftovers removed and a repeated question id renamed, or refused.
	 *
	 * @throws FormValidationException
	 */
	public function check(array $form): array {
		$cleaned = [];
		$form = $this->clean($form, $cleaned);
		$errors = $this->errors($form);
		if ($errors !== []) {
			throw FormValidationException::withErrors($errors);
		}
		if ($cleaned !== []) {
			$this->logger->info('FormVox: tidied a form on save', ['app' => 'formvox', 'form' => $form['id'] ?? null, 'cleaned' => $cleaned]);
		}
		return $form;
	}

	// ---- cleaning: what nobody can see in the editor ------------------------------------------------------------

	/**
	 * @param list<string> $cleaned what was removed, for the log
	 */
	private function clean(array $form, array &$cleaned): array {
		if (isset($form['descriptionAlign']) && !in_array($form['descriptionAlign'], self::ALIGNMENTS, true)) {
			$form['descriptionAlign'] = 'left';
			$cleaned[] = 'descriptionAlign';
		}
		if (is_array($form['questions'] ?? null) && array_is_list($form['questions'])) {
			$form = $this->renameRepeatedIds($form, $cleaned);
			// A loop, not array_map(fn): an arrow function would get a copy of $cleaned and the log would miss these.
			foreach ($form['questions'] as $i => $q) {
				if (is_array($q)) {
					$form['questions'][$i] = $this->cleanQuestion($q, $cleaned);
				}
			}
			$form = $this->cleanSections($form, $cleaned);
		}
		if (is_array($form['pages'] ?? null) && array_is_list($form['pages'])) {
			$form['pages'] = $this->cleanPages($form, $cleaned);
		}
		$form = $this->cleanBranding($form, $cleaned);
		if (is_array($form['settings'] ?? null)) {
			foreach ($form['settings'] as $key => $value) {
				if (!is_string($key) || !in_array($key, self::KNOWN_SETTINGS, true)) {
					unset($form['settings'][$key]);
					$cleaned[] = 'settings.' . (is_string($key) ? $key : 'list');
				}
			}
		}
		return $form;
	}

	/**
	 * A heading block's level becomes the tag the page draws, so only a heading level is kept (secu#8).
	 */
	private function cleanBranding(array $form, array &$cleaned): array {
		$layout = $form['branding']['layout'] ?? null;
		if (!is_array($layout)) {
			return $form;
		}
		foreach ($layout as $zone => $blocks) {
			foreach (is_array($blocks) ? $blocks : [] as $i => $block) {
				$level = is_array($block) && ($block['type'] ?? null) === 'heading' ? ($block['settings']['level'] ?? null) : null;
				if ($level !== null && !in_array($level, self::HEADING_LEVELS, true)) {
					$form['branding']['layout'][$zone][$i]['settings']['level'] = 'h1';
					$cleaned[] = "branding.$zone.$i.level";
				}
			}
		}
		return $form;
	}

	private function cleanQuestion(array $question, array &$cleaned): array {
		$type = $question['type'] ?? null;
		if (!is_string($type) || !isset(self::TYPE_FIELDS[$type])) {
			return $question;
		}
		// Older forms (the demo template, AI forms) said min/max; the page reads only the current names.
		foreach (self::OLD_NAMES[$type] ?? [] as $old => $current) {
			if (array_key_exists($old, $question)) {
				if (!isset($question[$current]) || $question[$current] === '') {
					$question[$current] = $question[$old];
				}
				unset($question[$old]);
				$cleaned[] = ($question['id'] ?? '?') . ".$old -> $current";
			}
		}
		$allowed = array_flip([...self::COMMON_FIELDS, ...self::TYPE_FIELDS[$type]]);
		foreach (array_keys($question) as $field) {
			if (!isset($allowed[$field])) {
				unset($question[$field]);
				$cleaned[] = ($question['id'] ?? '?') . ".$field";
			}
		}
		if (($question['showIf'] ?? null) === []) {
			$question['showIf'] = null;
		}
		return $question;
	}

	/**
	 * A question id used twice (AI forms, hand edits) shared one answer; the later question gets its own id,
	 * one piping still reads (\w). What referred to the id keeps referring to the first question.
	 */
	private function renameRepeatedIds(array $form, array &$cleaned): array {
		$taken = [];
		foreach ($form['questions'] as $q) {
			if (is_array($q) && is_string($q['id'] ?? null)) {
				$taken[$q['id']] = true;
			}
		}
		$seen = [];
		$renamed = []; // original id => [new ids in order]
		foreach ($form['questions'] as $i => $q) {
			$id = is_array($q) ? ($q['id'] ?? null) : null;
			if (!is_string($id) || $id === '') {
				continue;
			}
			if (!isset($seen[$id])) {
				$seen[$id] = true;
				continue;
			}
			$n = 2;
			while (isset($taken[$id . '_' . $n])) {
				$n++;
			}
			$new = $id . '_' . $n;
			$taken[$new] = true;
			$form['questions'][$i]['id'] = $new;
			$renamed[$id][] = $new;
			$cleaned[] = "$id -> $new";
		}
		if ($renamed === [] || !is_array($form['pages'] ?? null)) {
			return $form;
		}
		$mentions = [];
		foreach ($form['pages'] as $page) {
			foreach (is_array($page) && is_array($page['questions'] ?? null) ? $page['questions'] : [] as $qid) {
				if (is_string($qid) && isset($renamed[$qid])) {
					$mentions[$qid] = ($mentions[$qid] ?? 0) + 1;
				}
			}
		}
		// The n-th mention across the pages is the n-th question with that id; a single mention showed them all there.
		$seenMentions = [];
		foreach ($form['pages'] as $p => $page) {
			if (!is_array($page) || !is_array($page['questions'] ?? null)) {
				continue;
			}
			$list = [];
			foreach ($page['questions'] as $qid) {
				if (!is_string($qid) || !isset($renamed[$qid])) {
					$list[] = $qid;
					continue;
				}
				$nth = $seenMentions[$qid] = ($seenMentions[$qid] ?? 0) + 1;
				if ($mentions[$qid] === 1) {
					array_push($list, $qid, ...$renamed[$qid]);
				} else {
					$list[] = $nth === 1 ? $qid : ($renamed[$qid][$nth - 2] ?? $qid);
				}
			}
			$form['pages'][$p]['questions'] = $list;
		}
		return $form;
	}

	private function cleanSections(array $form, array &$cleaned): array {
		$sections = [];
		foreach ($form['questions'] as $q) {
			if (is_array($q) && ($q['type'] ?? null) === 'section' && is_string($q['id'] ?? null)) {
				$sections[$q['id']] = true;
			}
		}
		foreach ($form['questions'] as $i => $q) {
			if (is_array($q) && array_key_exists('sectionId', $q) && !(is_string($q['sectionId']) && isset($sections[$q['sectionId']]))) {
				unset($form['questions'][$i]['sectionId']);
				$cleaned[] = ($q['id'] ?? '?') . '.sectionId';
			}
		}
		return $form;
	}

	/**
	 * Page lists and page rules that name a deleted question or page: the editor leaves them behind.
	 */
	private function cleanPages(array $form, array &$cleaned): array {
		$questionIds = array_flip($this->questionIds($form));
		$pageIds = [];
		foreach ($form['pages'] as $page) {
			if (is_array($page) && is_string($page['id'] ?? null)) {
				$pageIds[$page['id']] = true;
			}
		}
		$placed = [];
		$pages = $form['pages'];
		foreach ($pages as $p => $page) {
			if (!is_array($page)) {
				continue;
			}
			if (is_array($page['questions'] ?? null)) {
				$kept = [];
				foreach ($page['questions'] as $qid) {
					if (is_string($qid) && isset($questionIds[$qid]) && !isset($placed[$qid])) {
						$kept[] = $qid;
						$placed[$qid] = true;
					} else {
						$cleaned[] = 'page ' . ($page['id'] ?? $p) . ' question ' . (is_scalar($qid) ? $qid : '?');
					}
				}
				$pages[$p]['questions'] = $kept;
			}
			if (is_array($page['routing'] ?? null)) {
				$rules = [];
				foreach ($page['routing'] as $rule) {
					if (is_array($rule) && is_string($rule['questionId'] ?? null) && isset($questionIds[$rule['questionId']])
						&& is_string($rule['targetPageId'] ?? null) && isset($pageIds[$rule['targetPageId']])) {
						$rules[] = $rule;
					} else {
						$cleaned[] = 'page ' . ($page['id'] ?? $p) . ' rule';
					}
				}
				$pages[$p]['routing'] = $rules;
			}
		}
		return $pages;
	}

	// ---- refusing: what would break the form ----------------------------------------------------------------------

	/**
	 * @return list<array{question: ?string, field: ?string, message: string}>
	 */
	private function errors(array $form): array {
		$errors = [];
		$add = function (?string $question, ?string $field, string $message) use (&$errors): void {
			$errors[] = ['question' => $question, 'field' => $field, 'message' => $message];
		};

		if (array_key_exists('title', $form) && !(is_string($form['title']) && mb_strlen($form['title']) <= self::MAX_TITLE)) {
			$add(null, 'title', $this->l->t('The title must be text of at most %s characters', [self::MAX_TITLE]));
		}
		if (array_key_exists('description', $form) && !is_string($form['description']) && $form['description'] !== null) {
			$add(null, 'description', $this->l->t('The description must be text'));
		}
		if (self::holdsInfinity($form)) {
			// TRANSLATORS: Error when a form file holds a number such as 1e999 that cannot be stored
			$add(null, null, $this->l->t('A number in the form is too large.'));
		}

		$questions = $form['questions'] ?? [];
		if (!is_array($questions) || !array_is_list($questions)) {
			$add(null, 'questions', $this->l->t('The questions must be a list'));
			$questions = [];
		} elseif (count($questions) > self::MAX_QUESTIONS) {
			$add(null, 'questions', $this->l->t('A form can have at most %s questions', [self::MAX_QUESTIONS]));
		}
		$ids = array_flip($this->questionIds($form));
		foreach ($questions as $question) {
			$this->questionErrors($question, $ids, $add);
		}

		$this->pageErrors($form['pages'] ?? null, $add);
		$this->settingErrors($form['settings'] ?? null, $add);

		if (array_key_exists('branding', $form) && $form['branding'] !== null && !is_array($form['branding'])) {
			$add(null, 'branding', $this->l->t('The branding is not valid'));
		}
		return $errors;
	}

	/**
	 * @param array<string, int> $ids
	 */
	private function questionErrors(mixed $q, array $ids, callable $add): void {
		if (!is_array($q) || !is_string($q['id'] ?? null) || preg_match('/^[\w-]{1,64}$/', $q['id']) !== 1) {
			$add(null, 'id', $this->l->t('Every question needs an id of letters, digits, - or _ (at most 64)'));
			return;
		}
		$id = $q['id'];
		$label = $this->label($q);
		$type = $q['type'] ?? null;
		if (!is_string($type) || !in_array($type, self::QUESTION_TYPES, true)) {
			$add($id, 'type', $this->l->t("Question '%s' has an unknown type", [$label]));
			return;
		}
		$invalid = fn (string $field) => $add($id, $field, $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, $field]));

		foreach (['question', 'description', 'placeholder', 'consentLabel'] as $field) {
			if (array_key_exists($field, $q) && !is_string($q[$field]) && $q[$field] !== null) {
				$invalid($field);
			}
		}
		foreach (['required', 'autoGenerated', 'useAsRespondentEmail', 'allowOther'] as $field) {
			if (array_key_exists($field, $q) && !is_bool($q[$field])) {
				$invalid($field);
			}
		}
		if (array_key_exists('color', $q) && !(is_string($q['color']) && preg_match(self::COLORS, $q['color']) === 1)) {
			$add($id, 'color', $this->l->t("Question '%s' has an invalid color", [$label]));
		}
		if (array_key_exists('descriptorAlign', $q) && !in_array($q['descriptorAlign'], self::ALIGNMENTS, true)) {
			$invalid('descriptorAlign');
		}

		if (($q['showIf'] ?? null) !== null) {
			$problem = $this->conditionProblem($q['showIf'], $ids, $id, 0);
			if ($problem === 'missing') {
				$add($id, 'showIf', $this->l->t("The condition of question '%s' refers to a question that no longer exists", [$label]));
			} elseif ($problem !== null) {
				$add($id, 'showIf', $this->l->t("The condition of question '%s' is not valid", [$label]));
			}
		}

		if (array_key_exists('validation', $q)) {
			$this->validationErrors($q['validation'], $id, $label, $add);
		}
		if (array_key_exists('maxLength', $q) && $q['maxLength'] !== null && !$this->isCount($q['maxLength'])) {
			$invalid('maxLength');
		}

		match ($type) {
			'choice', 'dropdown', 'multiple' => $this->optionErrors($q, $id, $label, $add),
			'number' => $this->rangeErrors($q, 'min', 'max', $id, $label, $add),
			'scale' => $this->scaleErrors($q, $id, $label, $add),
			'rating' => $this->ratingErrors($q, $id, $label, $add),
			'date', 'datetime' => $this->boundErrors($q, ['dateMin', 'dateMax'], fn ($v) => $this->isDate($v), $id, $add, $label),
			'time' => $this->boundErrors($q, ['timeMin', 'timeMax'], fn ($v) => is_string($v) && preg_match('/^([01]\d|2[0-3]):[0-5]\d$/', $v) === 1, $id, $add, $label),
			'matrix' => $this->matrixErrors($q, $id, $label, $add),
			'table' => $this->tableErrors($q, $id, $label, $add),
			'file' => $this->fileErrors($q, $id, $label, $add),
			default => null,
		};
	}

	/**
	 * @param array<string, int> $ids
	 * @return ?string null when fine, 'missing' for a question that does not exist, 'invalid' otherwise
	 */
	private function conditionProblem(mixed $c, array $ids, string $self, int $depth): ?string {
		if ($depth > self::MAX_CONDITION_DEPTH || !is_array($c)) {
			return 'invalid';
		}
		$operator = is_string($c['operator'] ?? null) ? $c['operator'] : null;
		if (!array_key_exists('questionId', $c) && in_array(strtolower((string)$operator), ['and', 'or'], true)) {
			$children = $c['conditions'] ?? null;
			if (!is_array($children) || $children === [] || !array_is_list($children)) {
				return 'invalid';
			}
			$missing = null;
			foreach ($children as $child) {
				$problem = $this->conditionProblem($child, $ids, $self, $depth + 1);
				if ($problem === 'invalid') {
					return 'invalid';
				}
				$missing ??= $problem;
			}
			return $missing;
		}
		$qid = $c['questionId'] ?? null;
		$value = $c['value'] ?? null;
		if (!is_string($qid) || $qid === '' || $qid === $self || !in_array($operator, self::OPERATORS, true)
			|| !($value === null || is_scalar($value) || (is_array($value) && array_filter($value, fn ($v) => !is_scalar($v)) === []))) {
			return 'invalid';
		}
		return isset($ids[$qid]) ? null : 'missing';
	}

	private function validationErrors(mixed $validation, string $id, string $label, callable $add): void {
		if ($validation === null) {
			return;
		}
		if (!is_array($validation)) {
			$add($id, 'validation', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'validation']));
			return;
		}
		$pattern = $validation['pattern'] ?? '';
		if (!is_string($pattern) || mb_strlen($pattern) > self::MAX_PATTERN || ($pattern !== '' && AnswerPattern::compile($pattern) === null)) {
			$add($id, 'validation.pattern', $this->l->t("The pattern of question '%s' is not a valid regular expression", [$label]));
		}
		if (array_key_exists('errorMessage', $validation) && !is_string($validation['errorMessage']) && $validation['errorMessage'] !== null) {
			$add($id, 'validation.errorMessage', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'validation.errorMessage']));
		}
	}

	private function optionErrors(array $q, string $id, string $label, callable $add): void {
		$options = $q['options'] ?? [];
		if (!is_array($options) || !array_is_list($options)) {
			$add($id, 'options', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'options']));
			return;
		}
		if (count($options) > self::MAX_OPTIONS) {
			$add($id, 'options', $this->l->t("Question '%1\$s' can have at most %2\$s options", [$label, self::MAX_OPTIONS]));
		}
		foreach ($options as $option) {
			if (!is_array($option)) {
				// A bare string is an older shape the editor still turns into an option when it opens the question.
				if (is_string($option)) {
					continue;
				}
				$add($id, 'options', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'options']));
				return;
			}
			$value = $option['value'] ?? $option['id'] ?? null;
			if (!is_scalar($value)
				|| (array_key_exists('label', $option) && !is_string($option['label']) && !is_numeric($option['label']) && $option['label'] !== null)
				|| (isset($option['capacity']) && $option['capacity'] !== '' && !$this->isCount($option['capacity']))
				|| (isset($option['score']) && !is_numeric($option['score']))) {
				$add($id, 'options', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'options']));
				return;
			}
		}
		if (($q['type'] ?? '') === 'multiple') {
			$this->rangeErrors($q, 'minSelections', 'maxSelections', $id, $label, $add, true);
		}
	}

	private function rangeErrors(array $q, string $low, string $high, string $id, string $label, callable $add, bool $whole = false): void {
		foreach ([$low, $high] as $field) {
			if (isset($q[$field]) && !($whole ? $this->isInt($q[$field], 0) : is_numeric($q[$field]) && !is_string($q[$field]))) {
				$add($id, $field, $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, $field]));
				return;
			}
		}
		if (isset($q[$low], $q[$high]) && $q[$low] > $q[$high]) {
			$add($id, $low, $this->l->t("In question '%1\$s', %2\$s is larger than %3\$s", [$label, $low, $high]));
		}
	}

	private function scaleErrors(array $q, string $id, string $label, callable $add): void {
		if (isset($q['scaleMin']) || isset($q['scaleMax'])) {
			$from = $q['scaleMin'] ?? 1;
			$to = $q['scaleMax'] ?? 5;
			if (!$this->isInt($from, 0) || $from > 1 || !$this->isInt($to, 1) || $to > self::SCALE_MAX || $to <= $from) {
				$add($id, 'scaleMin', $this->l->t("The scale of question '%1\$s' must start at 0 or 1 and end at %2\$s at most", [$label, self::SCALE_MAX]));
				return;
			}
		}
		foreach (['scaleMinLabel', 'scaleMaxLabel'] as $field) {
			if (array_key_exists($field, $q) && !is_string($q[$field]) && $q[$field] !== null) {
				$add($id, $field, $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, $field]));
			}
		}
	}

	private function ratingErrors(array $q, string $id, string $label, callable $add): void {
		if (isset($q['ratingMax']) && !($this->isInt($q['ratingMax'], 1) && $q['ratingMax'] <= self::RATING_MAX)) {
			$add($id, 'ratingMax', $this->l->t("Question '%1\$s' can have at most %2\$s stars", [$label, self::RATING_MAX]));
		}
	}

	/**
	 * @param list<string> $fields
	 */
	private function boundErrors(array $q, array $fields, callable $valid, string $id, callable $add, string $label): void {
		foreach ($fields as $field) {
			if (isset($q[$field]) && $q[$field] !== '' && !$valid($q[$field])) {
				$add($id, $field, $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, $field]));
			}
		}
	}

	private function matrixErrors(array $q, string $id, string $label, callable $add): void {
		foreach (['rows' => self::MAX_MATRIX_ROWS, 'columns' => self::MAX_MATRIX_COLUMNS] as $field => $max) {
			$items = $q[$field] ?? [];
			if (!$this->isListOf($items, fn ($item) => is_array($item) && (is_scalar($item['id'] ?? null) || is_scalar($item['value'] ?? null)))) {
				$add($id, $field, $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, $field]));
			} elseif (count($items) > $max) {
				$add($id, $field, $field === 'rows'
					? $this->l->t("Question '%1\$s' can have at most %2\$s rows", [$label, $max])
					: $this->l->t("Question '%1\$s' can have at most %2\$s columns", [$label, $max]));
			}
		}
	}

	private function tableErrors(array $q, string $id, string $label, callable $add): void {
		$columns = $q['columns'] ?? [];
		if (!$this->isListOf($columns, fn ($c) => is_array($c) && is_scalar($c['id'] ?? null)
			&& (!isset($c['inputType']) || in_array($c['inputType'], self::TABLE_INPUTS, true))
			&& (!isset($c['options']) || $this->isListOf($c['options'], 'is_scalar')))) {
			$add($id, 'columns', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'columns']));
		} elseif (count($columns) > self::MAX_TABLE_COLUMNS) {
			$add($id, 'columns', $this->l->t("Question '%1\$s' can have at most %2\$s columns", [$label, self::MAX_TABLE_COLUMNS]));
		}
		foreach (['minRows', 'maxRows'] as $field) {
			if (isset($q[$field]) && !($this->isInt($q[$field], 0) && $q[$field] <= self::MAX_TABLE_ROWS)) {
				$add($id, $field, $this->l->t("Question '%1\$s' can have at most %2\$s rows", [$label, self::MAX_TABLE_ROWS]));
				return;
			}
		}
	}

	private function fileErrors(array $q, string $id, string $label, callable $add): void {
		if (isset($q['allowedTypePreset']) && !in_array($q['allowedTypePreset'], self::FILE_PRESETS, true)) {
			$add($id, 'allowedTypePreset', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'allowedTypePreset']));
		}
		if (isset($q['allowedTypes']) && !$this->isListOf($q['allowedTypes'], 'is_string')) {
			$add($id, 'allowedTypes', $this->l->t("Question '%1\$s' has an invalid %2\$s", [$label, 'allowedTypes']));
		}
		$files = $q['maxFiles'] ?? 1;
		$size = $q['maxFileSize'] ?? 10;
		if (!($this->isInt($files, 1) && $files <= self::MAX_FILES) || !(is_numeric($size) && !is_string($size) && $size > 0 && $size <= self::MAX_FILE_SIZE_MB)) {
			$add($id, 'maxFileSize', $this->l->t("Question '%1\$s' can take at most %2\$s files of %3\$s MB each", [$label, self::MAX_FILES, self::MAX_FILE_SIZE_MB]));
		}
	}

	private function pageErrors(mixed $pages, callable $add): void {
		if ($pages === null) {
			return;
		}
		if (!is_array($pages) || !array_is_list($pages)) {
			$add(null, 'pages', $this->l->t('The pages must be a list'));
			return;
		}
		$seen = [];
		foreach ($pages as $page) {
			$pageId = is_array($page) ? ($page['id'] ?? null) : null;
			$valid = is_string($pageId) && $pageId !== '' && !isset($seen[$pageId])
				&& (!array_key_exists('title', $page) || is_string($page['title']) || $page['title'] === null)
				&& $this->isListOf($page['questions'] ?? [], 'is_string')
				&& $this->isListOf($page['routing'] ?? [], fn ($rule) => is_array($rule) && in_array($rule['operator'] ?? null, self::OPERATORS, true)
					&& (($rule['value'] ?? null) === null || is_scalar($rule['value'])));
			if (!$valid) {
				$add(null, 'pages', $this->l->t("Page '%s' is not valid", [is_array($page) && is_string($page['title'] ?? null) ? $page['title'] : (is_string($pageId) ? $pageId : '?')]));
				return;
			}
			$seen[$pageId] = true;
		}
	}

	private function settingErrors(mixed $settings, callable $add): void {
		if ($settings === null) {
			return;
		}
		if (!is_array($settings)) {
			$add(null, 'settings', $this->l->t('The settings must be an object'));
			return;
		}
		$isText = fn ($v) => $v === null || is_string($v);
		$rules = [
			'limit_message' => $isText, 'confirmationEmailSubject' => $isText, 'confirmationEmailBody' => $isText,
			'public_token' => $isText, 'share_password' => $isText,
			'share_expires_at' => fn ($v) => $v === null || $v === '' || $this->isDate($v),
			'share_starts_at' => fn ($v) => $v === null || $v === '' || $this->isDate($v),
			'max_responses' => fn ($v) => $v === null || $v === '' || $this->isInt($v, 0),
			'allowed_users' => fn ($v) => $this->isListOf($v, 'is_string'),
			'allowed_groups' => fn ($v) => $this->isListOf($v, 'is_string'),
			'notify_recipients' => fn ($v) => $this->isListOf($v, fn ($r) => is_array($r) && in_array($r['type'] ?? null, ['user', 'group'], true) && is_string($r['id'] ?? null)),
		];
		foreach (self::BOOLEAN_SETTINGS as $key) {
			$rules[$key] = 'is_bool';
		}
		foreach ($rules as $key => $valid) {
			if (array_key_exists($key, $settings) && !$valid($settings[$key])) {
				$add(null, "settings.$key", $this->l->t('The setting %s has an invalid value', [$key]));
			}
		}
	}

	// ---- helpers ------------------------------------------------------------------------------------------------

	/**
	 * @return list<string>
	 */
	private function questionIds(array $form): array {
		$ids = [];
		foreach (is_array($form['questions'] ?? null) ? $form['questions'] : [] as $q) {
			if (is_array($q) && is_string($q['id'] ?? null)) {
				$ids[] = $q['id'];
			}
		}
		return $ids;
	}

	/** A number like 1e999 reads as infinity, which cannot be written back: every later save of the form would fail. */
	private static function holdsInfinity(array $value): bool {
		foreach ($value as $item) {
			if ((is_float($item) && !is_finite($item)) || (is_array($item) && self::holdsInfinity($item))) {
				return true;
			}
		}
		return false;
	}

	private function label(array $q): string {
		$text = is_string($q['question'] ?? null) ? trim($q['question']) : '';
		return $text !== '' ? mb_substr($text, 0, 60) : (string)$q['id'];
	}

	private function isInt(mixed $value, int $min): bool {
		// The editor's number fields send floats like 5.0.
		return (is_int($value) || (is_float($value) && floor($value) === $value)) && $value >= $min;
	}

	/** A count the answer check casts to int anyway, so older forms may hold it as digits. */
	private function isCount(mixed $value): bool {
		return $this->isInt($value, 0) || (is_string($value) && ctype_digit($value));
	}

	private function isDate(mixed $value): bool {
		if (!is_string($value) || $value === '') {
			return false;
		}
		try {
			new \DateTimeImmutable($value);
			return preg_match('/^\d{4}-\d{2}-\d{2}/', $value) === 1;
		} catch (\Exception) {
			return false;
		}
	}

	private function isListOf(mixed $value, callable $each): bool {
		if (!is_array($value) || !array_is_list($value)) {
			return false;
		}
		foreach ($value as $item) {
			if (!$each($item)) {
				return false;
			}
		}
		return true;
	}
}
